struct Studio2FactoryInfo final : public CoreRegistry::FactoryInfo<Studio2, Studio2SetupInfo, Studio2Options>
{
    explicit Studio2FactoryInfo(const char* description)
        : FactoryInfo(350, studio2Presets, description)
    {}
    std::string prefix() const override
    {
        return "STUDIO2";
    }
    VariantIndex variantIndex(const Properties& props) const override
    {
        return {0, studio2Presets[0].options.asProperties() != props};
    }
};

static bool registeredStudio2 = CoreRegistry::registerFactory(PROP_CLASS, std::make_unique<Studio2FactoryInfo>("Hardware emulation of an RCA Studio II"));

class Studio2::Private {
public:
    explicit Private(EmulatorHost& host, Cdp1802Bus& bus, Properties& properties)
        : _host(host)
        , _properties(properties)
        , _options(Studio2Options::fromProperties(properties))
        , _cpu(bus, _options.clockFrequency)
        , _video(Cdp186x::eCDP1861, _cpu, false)
    {
        (void)registeredStudio2;
        _properties = _options.asProperties();
        _properties[PROP_ROM_NAME].setAdditionalInfo(fmt::format("(sha1: {})", calculateSha1(_studio2_rom).to_hex().substr(0,8)));
    }
    EmulatorHost& _host;
    Properties& _properties;
    Studio2Options _options;
    Cdp1802 _cpu;
    Cdp186x _video;
    uint8_t _keyLatch{0};
    bool _powerOn{true};
    float _wavePhase{0};
    // The CPU's view without mirrors: ROM at 0x000-0x7FF, RAM at 0x800-0x9FF.
    std::array<uint8_t, MEMORY_SIZE> _memory{};
};

