enum ST2VideoType { ST2_VT_CDP1861 };

struct Studio2Options
{
    Properties asProperties() const
    {
        auto result = registeredPrototype();
        result[PROP_TRACE_LOG].setBool(traceLog);
        result[PROP_CPU].setString(cpuType);
        result[PROP_CLOCK].setInt(clockFrequency);
        result[PROP_CLEAN_RAM].setBool(cleanRam);
        result[PROP_VIDEO].setSelectedIndex(toType(videoType));
        result[PROP_CRT_EFFECT].setBool(crtEffect);
        result[PROP_ROM_NAME].setString(romName);
        result.palette() = palette;
        return result;
    }
    static Studio2Options fromProperties(const Properties& props)
    {
        Studio2Options opts{};
        opts.traceLog = props[PROP_TRACE_LOG].getBool();
        opts.cpuType = props[PROP_CPU].getString();
        opts.clockFrequency = props[PROP_CLOCK].getInt();
        opts.cleanRam = props[PROP_CLEAN_RAM].getBool();
        opts.videoType = static_cast<ST2VideoType>(props[PROP_VIDEO].getSelectedIndex());
        opts.crtEffect = props[PROP_CRT_EFFECT].getBool();
        opts.romName = props[PROP_ROM_NAME].getString();
        opts.palette = props.palette();
        return opts;
    }
    static Properties& registeredPrototype()
    {
        using namespace std::string_literals;
        auto& prototype = Properties::getProperties(PROP_CLASS);
        if(!prototype) {
            prototype.registerProperty({PROP_TRACE_LOG, "Trace Log", false, "Enable trace log", PropertyFlags::eWritable});
            prototype.registerProperty({PROP_CPU, "CPU", "CDP1802"s, "CPU type (currently only cdp1802)"});
            prototype.registerProperty({PROP_CLOCK, "Clock Rate", Property::Integer{1760640, 100000, 500'000'000}, "Clock frequency, default is 1760640", PropertyFlags::eWritable});
            prototype.registerProperty({PROP_CLEAN_RAM, "Clean RAM", false, "Delete ram on startup", PropertyFlags::eWritable});
            prototype.registerProperty({PROP_VIDEO, "Video", Property::Combo{"CDP1861"}, "Video hardware, only cdp1861"});
            prototype.registerProperty({PROP_CRT_EFFECT, "CRT Effect", false, "Show the screen like a CRT with visible scan lines (display only)", PropertyFlags::eWritable});
            prototype.registerProperty(Property::separator());
            prototype.registerProperty({PROP_ROM_NAME, "ROM Name", "STUDIO-II"s, "Rom image name, default studio-ii"});
        }
        return prototype;
    }
    std::string cpuType;
    int clockFrequency;
    bool cleanRam;
    bool traceLog;
    ST2VideoType videoType;
    std::string romName;
    bool crtEffect{false};
    Palette palette;
};

