Studio2::Studio2(EmulatorHost& host, Properties& properties, IEmulationCore* other)
    : Chip8RealCoreBase(host)
    , _impl(new Private(host, *this, properties))
{
    if (auto otherStudio2 = dynamic_cast<Studio2*>(other)) {
        _impl->_cpu.swapBreakpoints(otherStudio2->_impl->_cpu);
    }
    _isHybridChipMode = false;
    _execChip8 = false;
    std::memcpy(_impl->_memory.data(), _studio2_rom, sizeof(_studio2_rom));

    _impl->_cpu.setInputHandler([this](uint8_t port) -> uint8_t {
        // Nothing drives the data bus on input, the pull-ups read high.
        ioCommand(port, 0xFF);
        return 0xFF;
    });
    _impl->_cpu.setOutputHandler([this](uint8_t port, uint8_t value) {
        ioCommand(port, value);
    });
    _impl->_cpu.setNEFInputHandler([this](uint8_t index) {
        switch (index) {
            case 0: return _impl->_video.getNEFX();
            case 2: return padKeyDown(0);
            case 3: return padKeyDown(1);
            default: return false;
        }
    });
}

Studio2::~Studio2() = default;

void Studio2::ioCommand(uint8_t port, uint8_t data)
{
    // DISP_ON is wired to N0 and the key decoder strobe to N1, so every I/O
    // instruction with these bits in N acts on them (the ROM uses INP 1 and OUT 2).
    if (port & 1) {
        _impl->_video.enableDisplay();
    }
    if (port & 2) {
        _impl->_keyLatch = data & 0x0F;
    }
}

bool Studio2::padKeyDown(int pad) const
{
    // Only the decoder outputs 0-9 are wired to the pads. Pad B has no host keys yet.
    return pad == 0 && _impl->_keyLatch < PAD_KEYS && _impl->_host.isKeyDown(_impl->_keyLatch);
}

void Studio2::handleReset(bool cold)
{
    if(_impl->_options.traceLog)
        Logger::log(Logger::eBACKEND_EMU, _impl->_cpu.cycles(), {_frames, frameCycle()}, "--- RESET ---");
    if (cold) {
        auto ram = std::span(_impl->_memory).subspan(ROM_SIZE);
        if (_impl->_options.cleanRam) {
            std::ranges::fill(ram, 0);
        }
        else if (_impl->_powerOn) {
            ghc::RandomLCG rnd(ghc::RandomLCG::Type::eNormal, 42);
            std::generate(ram.begin(), ram.end(), rnd);
        }
    }
    _impl->_powerOn = false;
    _isHybridChipMode = false;
    _execChip8 = false;
    _impl->_keyLatch = 0;
    _impl->_wavePhase = 0;
    _impl->_video.reset();
    _impl->_cpu.reset();
    _cycles = 0;
    _frames = 0;
    _state = {};
    _cpuState = eNORMAL;
    _errorMessage.clear();
    setExecMode(inErrorState() || !_host.isHeadless() ? ePAUSED : eRUNNING);
}

