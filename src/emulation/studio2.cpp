void Studio2::renderAudio(int16_t* samples, size_t frames, int sampleFrequency)
{
    if(_impl->_cpu.getQ()) {
        const float step = TONE_FREQUENCY / sampleFrequency;
        for (size_t i = 0; i < frames; ++i) {
            *samples++ = (_impl->_wavePhase < TONE_DUTY) ? 16384 : -16384;
            _impl->_wavePhase = std::fmod(_impl->_wavePhase + step, 1.0f);
        }
    }
    else {
        _impl->_wavePhase = 0;
        IEmulationCore::renderAudio(samples, frames, sampleFrequency);
    }
}

