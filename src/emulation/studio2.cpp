void Studio2::executeFrame()
{
    if (_execMode == ePAUSED || _cpuState == eERROR) {
        setExecMode(ePAUSED);
        return;
    }
    auto nextFrame = _impl->_video.nextFrame(_impl->_cpu.cycles());
    while(_execMode != ePAUSED && _impl->_cpu.cycles() < nextFrame) {
        executeCdp1802();
    }
}

